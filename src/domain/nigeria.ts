export function nigeriaAppointment(date: string, time: string) {
  // Nigeria uses UTC+01:00 throughout the year, regardless of browser timezone.
  return new Date(`${date}T${time}:00+01:00`).toISOString()
}

export function nigeriaToday() {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Africa/Lagos",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(new Date())
}
